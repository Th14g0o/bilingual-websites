const sessao = "linguagemprojetotadswukong";
let linguagemAtual = sessionStorage.getItem(sessao) ? sessionStorage.getItem(sessao) : "ptbr";

function setLinguagem(linguagem){
    sessionStorage.setItem(sessao, linguagem);
    linguagemAtual = linguagem;
    document.title = textos[linguagem]["siteTitulo"];
    document.querySelectorAll("[data-i18n]").forEach(elemento => {

        const chave = elemento.getAttribute("data-i18n");

        if (elemento.getAttribute("alt"))
            elemento.alt         = textos[linguagem][chave];
        else if (elemento.getAttribute("placeholder"))
            elemento.placeholder = textos[linguagem][chave];
        else if (elemento.getAttribute("type") && elemento.getAttribute("type") == "submit")
            elemento.value       = textos[linguagem][chave];
        else  
            elemento.textContent = textos[linguagem][chave];

        ajustarTexto()
    });
}

function ajustarTexto(){
    document.querySelectorAll("[data-i18n]").forEach(elemento => {
        const chave = elemento.getAttribute("data-i18n");
        elemento.textContent = textos[linguagemAtual][chave];
        if (["personagensArticle1Texto","personagensArticle2Texto", "personagensArticle3Texto", "personagensArticle4Texto"].indexOf(chave) != -1
            && window.innerWidth < 825
        ){
            const textoLimitado = elemento.textContent.substring(0, 200) + "...";
            if (elemento.getAttribute("alt"))
                elemento.alt         = textoLimitado;
            else if (elemento.getAttribute("placeholder"))
                elemento.placeholder = textoLimitado;
            else if (elemento.getAttribute("type") && elemento.getAttribute("type") == "submit")
                elemento.value       = textoLimitado;
            else  
                elemento.textContent = textoLimitado;
        }
    });
}


window.addEventListener("load", ajustarTexto);
